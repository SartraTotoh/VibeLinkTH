export function qrText(lang: Lang, key: QrTextKey): string {
  return (lang === "en" ? en[key] : th[key]) ?? th[key];
}

export function qrFmt(template: string, vars: Record<string, string | number>): string {
  let out = template;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
